app.post('/api/v46/shop/seed-products', async (req, res) => {
  try {
    const items = Array.isArray(req.body?.items) && req.body.items.length ? req.body.items : JAPANO_V46_SEED_PRODUCTS;
    const saved = [];
    const failed = [];
    for (const item of items) {
      try {
        const p = await v46UpsertShopProduct(item);
        saved.push(v46PublicProduct(p));
      } catch (e) {
        failed.push({ id: item.id || item.name, message: e.message });
        console.warn('[V46 seed product failed]', item.id || item.name, e.message);
      }
    }
    res.json({ ok: true, insertedOrUpdated: saved.length, failed, items: saved });
  } catch (e) {
    res.status(500).json({ ok: false, message: e.message });
  }
});

