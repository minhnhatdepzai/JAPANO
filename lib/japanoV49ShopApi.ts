export function v49BaseCandidates() {
  const envUrl =
    typeof process !== 'undefined' && process.env?.EXPO_PUBLIC_API_URL
      ? String(process.env.EXPO_PUBLIC_API_URL)
      : '';

  return Array.from(new Set([
    envUrl,
    'http://10.0.2.2:4000',
    'http://127.0.0.1:4000',
    'http://localhost:4000',
  ].filter(Boolean).map((x) => x.replace(/\/+$/, ''))));
}

export async function v49FetchJson(path: string, options: any = {}, fallbackValue?: any) {
  let lastErr: any = null;
  for (const base of v49BaseCandidates()) {
    try {
      const res = await fetch(`${base}${path}`, options);
      const text = await res.text();
      const data = text ? JSON.parse(text) : {};
      if (!res.ok) throw new Error(data?.message || text || `HTTP ${res.status}`);
      return data;
    } catch (e) {
      lastErr = e;
    }
  }
  if (fallbackValue !== undefined) return fallbackValue;
  throw lastErr || new Error('Network request failed');
}

export async function v49Get(path: string, fallbackValue?: any) {
  return v49FetchJson(path, undefined, fallbackValue);
}

export async function v49Post(path: string, body: any, fallbackValue?: any) {
  return v49FetchJson(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  }, fallbackValue);
}

