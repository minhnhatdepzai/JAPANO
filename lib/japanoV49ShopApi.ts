  const hi = Number(hip || 0);
  const bu = Number(bust || 0);
  let score = 0;

  if (w <= 47) score = 0;
  else if (w <= 54) score = 1;
  else if (w <= 61) score = 2;
  else if (w <= 68) score = 3;
  else if (w <= 76) score = 4;
  else score = 5;

  if (wa >= 92 || hi >= 112 || bu >= 106) score = Math.max(score, 5);
  else if (wa >= 84 || hi >= 106 || bu >= 100) score = Math.max(score, 4);
  else if (wa >= 78 || hi >= 100 || bu >= 94) score = Math.max(score, 3);
